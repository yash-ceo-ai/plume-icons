// Builds dist/ from icons/: plain SVG files, the Iconify collection, the core JS data, React components and the
// Astro component. Run: npm run build
import { mkdirSync, rmSync, writeFileSync, readFileSync, copyFileSync } from 'node:fs';
import { join } from 'node:path';
import { CATEGORIES, VARIANTS, checkDir, innerMarkup, minify, parse, pascal, readSource, rootAttrString } from './lib.mjs';

const root = new URL('..', import.meta.url).pathname;
const src = join(root, 'icons');
const dist = join(root, 'dist');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

const errors = checkDir(src);
if (errors.length) {
  console.error(`plume build: fix these first (npm run check)\n${errors.map((e) => `  ${e}`).join('\n')}`);
  process.exit(1);
}

const { files, meta } = readSource(src);
const names = Object.keys(files).sort();
/** name -> { line, fill } inner markup with %id% placeholders */
const bodies = {};
for (const name of names) {
  bodies[name] = {};
  for (const v of VARIANTS) bodies[name][v] = innerMarkup(parse(minify(files[name][v])));
}

rmSync(dist, { recursive: true, force: true });
for (const d of ['svg/line', 'svg/fill', 'react/icons', 'astro']) mkdirSync(join(dist, d), { recursive: true });
const write = (p, s) => writeFileSync(join(dist, p), s);
const idFor = (name, v) => `plume-${name}-${v}-`;
const fixed = (body, name, v) => body.split('%id%').join(idFor(name, v));
const banner = `// plume-icons ${pkg.version}, MIT. Generated by scripts/build.mjs; do not edit.\n`;

// 1. Plain SVG files
for (const name of names) for (const v of VARIANTS) {
  write(`svg/${v}/${name}.svg`, `<svg ${rootAttrString()}>${fixed(bodies[name][v], name, v)}</svg>\n`);
}

// 2. Iconify collection (prefix "plume"; icons "<name>-line" and "<name>-fill")
const wrap = (body) => `<g fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">${body}</g>`;
const iconify = {
  prefix: 'plume',
  info: {
    name: 'Plume Icons',
    total: names.length * VARIANTS.length,
    version: pkg.version,
    author: { name: 'yash-ceo-ai', url: 'https://github.com/yash-ceo-ai/plume-icons' },
    license: { title: 'MIT', spdx: 'MIT', url: 'https://github.com/yash-ceo-ai/plume-icons/blob/main/LICENSE' },
    samples: ['search-line', 'chats-line', 'gear-line'].filter((s) => bodies[s.replace(/-line$/, '')]),
    height: 24,
    category: 'General',
    palette: false,
  },
  icons: {},
  categories: {},
  width: 24,
  height: 24,
};
for (const name of names) for (const v of VARIANTS) iconify.icons[`${name}-${v}`] = { body: wrap(fixed(bodies[name][v], name, v)) };
for (const c of CATEGORIES) {
  const list = names.filter((n) => meta[n].category === c).flatMap((n) => VARIANTS.map((v) => `${n}-${v}`));
  if (list.length) iconify.categories[c[0].toUpperCase() + c.slice(1)] = list;
}
write('plume.json', JSON.stringify(iconify));

// 3. Meta (categories, tags, Phosphor and Lucide equivalents) for search and the docs site
write('meta.json', JSON.stringify({ version: pkg.version, categories: CATEGORIES, icons: Object.fromEntries(names.map((n) => [n, meta[n]])) }, null, 2));

// 4. Core: data + toSvg()
const nameUnion = names.map((n) => `'${n}'`).join(' | ');
write('data.js', `${banner}export const icons = ${JSON.stringify(bodies)};\n`);
write('data.d.ts', `export type IconName = ${nameUnion};\nexport type IconVariant = 'line' | 'fill';\n/** Inner SVG markup per icon; "%id%" marks mask ids that must be made unique per render. */\nexport declare const icons: Record<IconName, Record<IconVariant, string>>;\n`);
write('index.js', `${banner}import { icons } from './data.js';
export { icons };
export const iconNames = Object.keys(icons);
let n = 0;
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');
/** An icon as an SVG string, for code that builds HTML (vanilla JS, server templates, email). */
export function toSvg(name, options = {}) {
  const data = icons[name];
  if (!data) throw new Error('plume-icons: unknown icon "' + name + '"');
  const { variant = 'line', size = 24, strokeWidth = 1.8, title, attrs = {} } = options;
  const cls = ['plume', 'plume-' + name, options.class].filter(Boolean).join(' ');
  const id = 'plume-' + name + '-' + (n = (n + 1) % 1e9).toString(36) + '-';
  const extra = Object.entries(attrs).map(([k, v]) => ' ' + k + '="' + esc(v) + '"').join('');
  const a11y = title ? ' role="img"' : ' aria-hidden="true"';
  return '<svg xmlns="http://www.w3.org/2000/svg" width="' + esc(size) + '" height="' + esc(size) + '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="' + esc(strokeWidth) + '" stroke-linecap="round" stroke-linejoin="round" class="' + esc(cls) + '"' + a11y + extra + '>' + (title ? '<title>' + esc(title) + '</title>' : '') + data[variant].split('%id%').join(id) + '</svg>';
}
`);
write('index.d.ts', `export { icons, type IconName, type IconVariant } from './data.js';
import type { IconName, IconVariant } from './data.js';
export declare const iconNames: IconName[];
export interface ToSvgOptions {
  variant?: IconVariant;
  size?: number | string;
  strokeWidth?: number | string;
  class?: string;
  /** Accessible name; without it the SVG gets aria-hidden="true". */
  title?: string;
  /** Extra attributes for the <svg> element. */
  attrs?: Record<string, string | number>;
}
/** An icon as an SVG string, for code that builds HTML (vanilla JS, server templates, email). */
export declare function toSvg(name: IconName, options?: ToSvgOptions): string;
`);

// 5. React: one module per icon (tree-shakable), the generic <Icon>, and the factory
copyFileSync(join(root, 'src/react/create.js'), join(dist, 'react/create.js'));
copyFileSync(join(root, 'src/react/Icon.js'), join(dist, 'react/Icon.js'));
let reactIndex = `${banner}export { createPlumeIcon } from './create.js';\nexport { Icon } from './Icon.js';\n`;
let reactTypes = `import type { ForwardRefExoticComponent, RefAttributes, SVGProps } from 'react';
import type { IconName, IconVariant } from '../data.js';
export type { IconName, IconVariant };
export interface PlumeIconProps extends Omit<SVGProps<SVGSVGElement>, 'ref' | 'children'> {
  /** Width and height (default 24). */
  size?: number | string;
  /** "line" (default) or "fill". */
  variant?: IconVariant;
  /** Line weight on the 24 grid (default 1.8). */
  strokeWidth?: number | string;
  /** Accessible name. Without it (or aria-label) the icon is hidden from screen readers. */
  title?: string;
}
export type PlumeIcon = ForwardRefExoticComponent<PlumeIconProps & RefAttributes<SVGSVGElement>>;
/** Picks the icon by name at run time; loads every icon, so prefer the named components. */
export declare const Icon: ForwardRefExoticComponent<PlumeIconProps & { name: IconName } & RefAttributes<SVGSVGElement>>;
/** Make a component from your own { line, fill } inner markup. */
export declare function createPlumeIcon(name: string, data: { line: string; fill?: string }, displayName?: string): PlumeIcon;
`;
for (const name of names) {
  const C = pascal(name);
  write(`react/icons/${name}.js`, `${banner}import { createPlumeIcon } from '../create.js';\nexport const ${C} = /* @__PURE__ */ createPlumeIcon(${JSON.stringify(name)}, ${JSON.stringify(bodies[name])}, ${JSON.stringify(C)});\n`);
  reactIndex += `export { ${C}, ${C} as ${C}Icon } from './icons/${name}.js';\n`;
  reactTypes += `export declare const ${C}: PlumeIcon;\nexport declare const ${C}Icon: PlumeIcon;\n`;
}
write('react/index.js', reactIndex);
write('react/index.d.ts', reactTypes);

// 6. Astro: the component reads the same data
copyFileSync(join(root, 'src/astro/Icon.astro'), join(dist, 'astro/Icon.astro'));
copyFileSync(join(root, 'src/astro/uid.js'), join(dist, 'astro/uid.js'));

console.log(`plume build: ${names.length} icons (${names.length * VARIANTS.length} SVGs) -> dist/`);
